const FAQ_SAMPLE = `# ZgentFlow 使用 FAQ

## 启动与运行

### Q1: 后端如何启动？

在 Linux amd64 环境执行 \`make dev-app\`。脚本会准备 PostgreSQL、Redis、文档解析服务和 Go 后端，不需要 Docker。

### Q2: 前端如何启动？

执行 \`make dev-frontend\`，浏览器访问 \`http://127.0.0.1:5173\`。后端默认地址是 \`http://127.0.0.1:8081\`。

### Q3: 8081 端口被占用怎么办？

可以执行 \`make dev-app ZEALRAG_APP_PORT=8082\`，启动前端时使用相同端口变量。停止项目本地进程使用 \`make dev-stop\`。

## 文档与索引

### Q4: 文档长时间停留在处理中怎么办？

先查看页面中的处理阶段和失败原因，再检查 \`.runtime/logs\` 下的后端与 docreader 日志。加密 PDF、损坏文件或模型请求超时都会导致解析失败。

### Q5: 为什么检索结果为空？

确认文档已经完成处理，知识库启用了向量或关键词索引，并且嵌入模型可用。必要时在知识库中执行完整重建。

### Q6: 可以切换向量数据库吗？

不可以。第一版固定使用 PostgreSQL + pgvector，以减少部署组件和配置分支。原始文件固定保存在本地文件系统。

### Q7: 如何改善召回质量？

先调整分块大小和重叠比例，再配置重排模型。标题清晰的 Markdown 或制度文档适合结构感知分块；长段落文本可以使用父子分块保留上下文。

## FAQ 知识库

### Q8: FAQ 知识库适合什么内容？

FAQ 知识库适合结构化问题与答案，例如客服话术、产品说明和内部流程问答。FAQ 会保留原始文本分块，并单独参与召回。

### Q9: FAQ 问题生成失败后怎么办？

失败记录会保留，可以在补充可用模型后单独重试问题生成，不需要重新导入原始内容。`

